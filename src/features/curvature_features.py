CURVATURE_STATISTICS = (
    "sum",
    "mean",
    "std",
    "min",
    "max",
)


def _scale_label(
    scale: float,
) -> str:
    """
    Convert a numeric scale into a stable feature-name label.

    Examples
    --------
    0.5 -> "0p5"
    1.0 -> "1"
    2.0 -> "2"
    """

    return (
        f"{float(scale):g}"
        .replace(".", "p")
    )


def gaussian_density_derivatives(
    evaluation_coords: np.ndarray,
    source_coords: np.ndarray,
    scale: float,
    exclude_self_mask: np.ndarray | None = None,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    """
    Evaluate a Gaussian density field together with its gradient
    and Hessian.

    The density generated by source atoms is

        rho(r) = sum_j exp(-||r - r_j||^2 / scale^2)

    Parameters
    ----------
    evaluation_coords : np.ndarray
        Coordinates where the density is evaluated.
        Shape: (n_target, 3)

    source_coords : np.ndarray
        Coordinates of atoms generating the density field.
        Shape: (n_source, 3)

    scale : float
        Gaussian spatial scale in Angstroms.

    exclude_self_mask : np.ndarray or None
        Boolean matrix of shape (n_target, n_source).

        True indicates that a target-source interaction should
        be excluded. This is used for same-element channels to
        remove an atom's self-contribution.

    Returns
    -------
    density : np.ndarray
        Density evaluated at every target point.
        Shape: (n_target,)

    gradient : np.ndarray
        Gradient of the density field.
        Shape: (n_target, 3)

    hessian : np.ndarray
        Hessian of the density field.
        Shape: (n_target, 3, 3)
    """

    evaluation_coords = np.asarray(
        evaluation_coords,
        dtype=float,
    )

    source_coords = np.asarray(
        source_coords,
        dtype=float,
    )

    if scale <= 0:
        raise ValueError(
            "scale must be greater than 0."
        )

    if (
        evaluation_coords.ndim != 2
        or evaluation_coords.shape[1] != 3
    ):
        raise ValueError(
            "evaluation_coords must have "
            "shape (n_target, 3)."
        )

    if (
        source_coords.ndim != 2
        or source_coords.shape[1] != 3
    ):
        raise ValueError(
            "source_coords must have "
            "shape (n_source, 3)."
        )

    n_target = evaluation_coords.shape[0]
    n_source = source_coords.shape[0]

    # No evaluation points.
    if n_target == 0:
        return (
            np.empty(
                0,
                dtype=float,
            ),
            np.empty(
                (0, 3),
                dtype=float,
            ),
            np.empty(
                (0, 3, 3),
                dtype=float,
            ),
        )

    # Target atoms exist but no source atoms exist.
    if n_source == 0:
        return (
            np.zeros(
                n_target,
                dtype=float,
            ),
            np.zeros(
                (n_target, 3),
                dtype=float,
            ),
            np.zeros(
                (n_target, 3, 3),
                dtype=float,
            ),
        )

    if exclude_self_mask is not None:

        exclude_self_mask = np.asarray(
            exclude_self_mask,
            dtype=bool,
        )

        expected_shape = (
            n_target,
            n_source,
        )

        if exclude_self_mask.shape != expected_shape:
            raise ValueError(
                "exclude_self_mask must have shape "
                f"{expected_shape}."
            )

    # q_ij = r_i - r_j
    #
    # Shape:
    # (n_target, n_source, 3)
    differences = (
        evaluation_coords[:, None, :]
        - source_coords[None, :, :]
    )

    squared_distances = np.sum(
        differences**2,
        axis=2,
    )

    inverse_scale_squared = (
        1.0 / scale**2
    )

    # phi_ij =
    # exp(-||r_i-r_j||^2 / eta^2)
    #
    # Shape:
    # (n_target, n_source)
    kernel_values = np.exp(
        -squared_distances
        * inverse_scale_squared
    )

    if exclude_self_mask is not None:

        kernel_values = (
            kernel_values.copy()
        )

        kernel_values[
            exclude_self_mask
        ] = 0.0

    # --------------------------------------------------
    # Density
    # --------------------------------------------------

    density = np.sum(
        kernel_values,
        axis=1,
    )

    # --------------------------------------------------
    # Gradient
    #
    # ∇phi =
    # -2 / eta^2 * q * phi
    # --------------------------------------------------

    gradient_contributions = (
        -2.0
        * inverse_scale_squared
        * differences
        * kernel_values[:, :, None]
    )

    gradient = np.sum(
        gradient_contributions,
        axis=1,
    )

    # --------------------------------------------------
    # Hessian
    #
    # Hess(phi) =
    #
    # [
    #   4 / eta^4 * q q^T
    #   -
    #   2 / eta^2 * I
    # ] * phi
    # --------------------------------------------------

    outer_products = (
        differences[:, :, :, None]
        * differences[:, :, None, :]
    )

    identity = np.eye(
        3,
        dtype=float,
    )

    hessian_contributions = (
        (
            4.0
            * inverse_scale_squared**2
            * outer_products
            -
            2.0
            * inverse_scale_squared
            * identity[None, None, :, :]
        )
        * kernel_values[
            :, :, None, None
        ]
    )

    hessian = np.sum(
        hessian_contributions,
        axis=1,
    )

    return (
        density,
        gradient,
        hessian,
    )


def mean_curvature(
    gradient: np.ndarray,
    hessian: np.ndarray,
    gradient_epsilon: float = 1e-12,
) -> tuple[
    np.ndarray,
    np.ndarray,
]:
    """
    Compute mean curvature H of the implicit density surface.

    Curvature is defined only where the density gradient is
    sufficiently nonzero.

    Parameters
    ----------
    gradient : np.ndarray
        Density gradient.
        Shape: (n_points, 3)

    hessian : np.ndarray
        Density Hessian.
        Shape: (n_points, 3, 3)

    gradient_epsilon : float
        Minimum allowed ||gradient|| for a point to be treated
        as a regular point of the implicit surface.

    Returns
    -------
    curvature : np.ndarray
        Mean curvature at every point. Invalid points are NaN.

    valid_mask : np.ndarray
        Boolean mask indicating points where curvature is defined.
    """

    gradient = np.asarray(
        gradient,
        dtype=float,
    )

    hessian = np.asarray(
        hessian,
        dtype=float,
    )

    if (
        gradient.ndim != 2
        or gradient.shape[1] != 3
    ):
        raise ValueError(
            "gradient must have shape (n_points, 3)."
        )

    if hessian.shape != (
        gradient.shape[0],
        3,
        3,
    ):
        raise ValueError(
            "hessian must have shape "
            "(n_points, 3, 3)."
        )

    if gradient_epsilon < 0:
        raise ValueError(
            "gradient_epsilon must be non-negative."
        )

    rho_x = gradient[:, 0]
    rho_y = gradient[:, 1]
    rho_z = gradient[:, 2]

    rho_xx = hessian[:, 0, 0]
    rho_xy = hessian[:, 0, 1]
    rho_xz = hessian[:, 0, 2]

    rho_yy = hessian[:, 1, 1]
    rho_yz = hessian[:, 1, 2]

    rho_zz = hessian[:, 2, 2]

    gradient_norm_squared = (
        rho_x**2
        + rho_y**2
        + rho_z**2
    )

    gradient_norm = np.sqrt(
        gradient_norm_squared
    )

    valid_mask = (
        gradient_norm
        > gradient_epsilon
    )

    curvature = np.full(
        gradient.shape[0],
        np.nan,
        dtype=float,
    )

    numerator = (
        2.0
        * rho_x
        * rho_y
        * rho_xy
        +
        2.0
        * rho_x
        * rho_z
        * rho_xz
        +
        2.0
        * rho_y
        * rho_z
        * rho_yz
        -
        (
            rho_y**2
            + rho_z**2
        )
        * rho_xx
        -
        (
            rho_x**2
            + rho_z**2
        )
        * rho_yy
        -
        (
            rho_x**2
            + rho_y**2
        )
        * rho_zz
    )

    denominator = (
        2.0
        * gradient_norm_squared**1.5
    )

    curvature[
        valid_mask
    ] = (
        numerator[valid_mask]
        / denominator[valid_mask]
    )

    valid_mask &= np.isfinite(
        curvature
    )

    return (
        curvature,
        valid_mask,
    )


def gaussian_curvature(
    gradient: np.ndarray,
    hessian: np.ndarray,
    gradient_epsilon: float = 1e-12,
) -> tuple[
    np.ndarray,
    np.ndarray,
]:
    """
    Compute Gaussian curvature K of the implicit density surface.

    Curvature is defined only where the density gradient is
    sufficiently nonzero.

    Returns
    -------
    curvature : np.ndarray
        Gaussian curvature at every point.
        Invalid points are NaN.

    valid_mask : np.ndarray
        Boolean mask identifying regular evaluation points.
    """

    gradient = np.asarray(
        gradient,
        dtype=float,
    )

    hessian = np.asarray(
        hessian,
        dtype=float,
    )

    if (
        gradient.ndim != 2
        or gradient.shape[1] != 3
    ):
        raise ValueError(
            "gradient must have shape (n_points, 3)."
        )

    if hessian.shape != (
        gradient.shape[0],
        3,
        3,
    ):
        raise ValueError(
            "hessian must have shape "
            "(n_points, 3, 3)."
        )

    if gradient_epsilon < 0:
        raise ValueError(
            "gradient_epsilon must be non-negative."
        )

    rho_x = gradient[:, 0]
    rho_y = gradient[:, 1]
    rho_z = gradient[:, 2]

    rho_xx = hessian[:, 0, 0]
    rho_xy = hessian[:, 0, 1]
    rho_xz = hessian[:, 0, 2]

    rho_yy = hessian[:, 1, 1]
    rho_yz = hessian[:, 1, 2]

    rho_zz = hessian[:, 2, 2]

    gradient_norm_squared = (
        rho_x**2
        + rho_y**2
        + rho_z**2
    )

    gradient_norm = np.sqrt(
        gradient_norm_squared
    )

    valid_mask = (
        gradient_norm
        > gradient_epsilon
    )

    curvature = np.full(
        gradient.shape[0],
        np.nan,
        dtype=float,
    )

    numerator = (
        2.0
        * rho_x
        * rho_y
        * rho_xz
        * rho_yz
        +
        2.0
        * rho_x
        * rho_z
        * rho_xy
        * rho_yz
        +
        2.0
        * rho_y
        * rho_z
        * rho_xy
        * rho_xz

        -
        2.0
        * rho_x
        * rho_z
        * rho_xz
        * rho_yy

        -
        2.0
        * rho_y
        * rho_z
        * rho_xx
        * rho_yz

        -
        2.0
        * rho_x
        * rho_y
        * rho_xy
        * rho_zz

        +
        rho_z**2
        * rho_xx
        * rho_yy

        +
        rho_x**2
        * rho_yy
        * rho_zz

        +
        rho_y**2
        * rho_xx
        * rho_zz

        -
        rho_x**2
        * rho_yz**2

        -
        rho_y**2
        * rho_xz**2

        -
        rho_z**2
        * rho_xy**2
    )

    denominator = (
        gradient_norm_squared**2
    )

    curvature[
        valid_mask
    ] = (
        numerator[valid_mask]
        / denominator[valid_mask]
    )

    valid_mask &= np.isfinite(
        curvature
    )

    return (
        curvature,
        valid_mask,
    )


def element_curvature_at_atoms(
    coords: np.ndarray,
    symbols: np.ndarray,
    target_element: str,
    source_element: str,
    scale: float,
    gradient_epsilon: float = 1e-12,
    exclude_self: bool = True,
) -> dict[str, np.ndarray]:
    """
    Calculate element-interactive curvatures at target atoms.

    Example
    -------
    target_element = "C"
    source_element = "O"

    evaluates the geometry of the oxygen-generated density
    field at carbon atomic positions.

    Returns
    -------
    dict
        Contains:

        density
        gradient
        hessian
        H
        K
        valid
    """

    coords = np.asarray(
        coords,
        dtype=float,
    )

    symbols = np.asarray(
        symbols,
    )

    if (
        coords.ndim != 2
        or coords.shape[1] != 3
    ):
        raise ValueError(
            "coords must have shape (n_atoms, 3)."
        )

    if len(symbols) != len(coords):
        raise ValueError(
            "symbols and coords must have "
            "the same number of atoms."
        )

    target_indices = np.flatnonzero(
        symbols == target_element
    )

    source_indices = np.flatnonzero(
        symbols == source_element
    )

    target_coords = coords[
        target_indices
    ]

    source_coords = coords[
        source_indices
    ]

    self_mask = None

    if exclude_self:

        self_mask = (
            target_indices[:, None]
            == source_indices[None, :]
        )

    (
        density,
        gradient,
        hessian,
    ) = gaussian_density_derivatives(
        evaluation_coords=target_coords,
        source_coords=source_coords,
        scale=scale,
        exclude_self_mask=self_mask,
    )

    (
        mean_values,
        mean_valid,
    ) = mean_curvature(
        gradient=gradient,
        hessian=hessian,
        gradient_epsilon=gradient_epsilon,
    )

    (
        gaussian_values,
        gaussian_valid,
    ) = gaussian_curvature(
        gradient=gradient,
        hessian=hessian,
        gradient_epsilon=gradient_epsilon,
    )

    valid_mask = (
        mean_valid
        & gaussian_valid
        & np.isfinite(mean_values)
        & np.isfinite(gaussian_values)
    )

    return {
        "density": density,
        "gradient": gradient,
        "hessian": hessian,
        "H": mean_values,
        "K": gaussian_values,
        "valid": valid_mask,
    }


def aggregate_curvature_values(
    values: np.ndarray,
    valid_mask: np.ndarray,
) -> dict[str, float]:
    """
    Aggregate atom-level curvature values into fixed-size
    molecular features.

    Invalid or non-finite curvature values are excluded.

    Returns
    -------
    dict
        sum
        mean
        std
        min
        max
        valid_fraction
    """

    values = np.asarray(
        values,
        dtype=float,
    ).ravel()

    valid_mask = np.asarray(
        valid_mask,
        dtype=bool,
    ).ravel()

    if values.shape != valid_mask.shape:
        raise ValueError(
            "values and valid_mask must "
            "have the same shape."
        )

    n_total = values.size

    if n_total == 0:
        return {
            "sum": 0.0,
            "mean": 0.0,
            "std": 0.0,
            "min": 0.0,
            "max": 0.0,
            "valid_fraction": 0.0,
        }

    final_mask = (
        valid_mask
        & np.isfinite(values)
    )

    valid_values = values[
        final_mask
    ]

    valid_fraction = (
        valid_values.size
        / n_total
    )

    if valid_values.size == 0:
        return {
            "sum": 0.0,
            "mean": 0.0,
            "std": 0.0,
            "min": 0.0,
            "max": 0.0,
            "valid_fraction": 0.0,
        }

    return {
        "sum": float(
            np.sum(valid_values)
        ),
        "mean": float(
            np.mean(valid_values)
        ),
        "std": float(
            np.std(valid_values)
        ),
        "min": float(
            np.min(valid_values)
        ),
        "max": float(
            np.max(valid_values)
        ),
        "valid_fraction": float(
            valid_fraction
        ),
    }


def curvature_feature_names(
    channels: list[tuple[str, str]],
    scales: np.ndarray,
    statistics: tuple[str, ...] = CURVATURE_STATISTICS,
) -> list[str]:
    """
    Generate deterministic names for all G5 features.
    """

    valid_statistics = set(
        CURVATURE_STATISTICS
    )

    unknown_statistics = (
        set(statistics)
        - valid_statistics
    )

    if unknown_statistics:
        raise ValueError(
            "Unknown curvature statistics: "
            f"{unknown_statistics}"
        )

    names = []

    for target_element, source_element in channels:

        for scale in scales:

            scale_label = _scale_label(
                scale
            )

            for curvature_name in (
                "H",
                "K",
            ):

                for statistic in statistics:

                    names.append(
                        f"curvature_"
                        f"{target_element}_"
                        f"from_{source_element}_"
                        f"eta{scale_label}_"
                        f"{curvature_name}_"
                        f"{statistic}"
                    )

            names.append(
                f"curvature_"
                f"{target_element}_"
                f"from_{source_element}_"
                f"eta{scale_label}_"
                f"valid_fraction"
            )

    return names


def element_channel_curvature_features(
    coords: np.ndarray,
    symbols: np.ndarray,
    channels: list[tuple[str, str]],
    scales: np.ndarray,
    gradient_epsilon: float = 1e-12,
) -> dict[str, float]:
    """
    Compute multiscale mean and Gaussian curvature features
    for every directed element interaction channel.
    """

    scales = np.asarray(
        scales,
        dtype=float,
    )

    if scales.ndim != 1:
        raise ValueError(
            "scales must be a one-dimensional array."
        )

    if np.any(scales <= 0):
        raise ValueError(
            "all scales must be greater than 0."
        )

    features = {}

    for target_element, source_element in channels:

        for scale in scales:

            curvature_data = (
                element_curvature_at_atoms(
                    coords=coords,
                    symbols=symbols,
                    target_element=target_element,
                    source_element=source_element,
                    scale=float(scale),
                    gradient_epsilon=gradient_epsilon,
                    exclude_self=True,
                )
            )

            valid_mask = (
                curvature_data["valid"]
            )

            H_statistics = (
                aggregate_curvature_values(
                    values=curvature_data["H"],
                    valid_mask=valid_mask,
                )
            )

            K_statistics = (
                aggregate_curvature_values(
                    values=curvature_data["K"],
                    valid_mask=valid_mask,
                )
            )

            scale_label = _scale_label(
                scale
            )

            for statistic in CURVATURE_STATISTICS:

                H_name = (
                    f"curvature_"
                    f"{target_element}_"
                    f"from_{source_element}_"
                    f"eta{scale_label}_"
                    f"H_{statistic}"
                )

                features[
                    H_name
                ] = H_statistics[
                    statistic
                ]

                K_name = (
                    f"curvature_"
                    f"{target_element}_"
                    f"from_{source_element}_"
                    f"eta{scale_label}_"
                    f"K_{statistic}"
                )

                features[
                    K_name
                ] = K_statistics[
                    statistic
                ]

            valid_fraction_name = (
                f"curvature_"
                f"{target_element}_"
                f"from_{source_element}_"
                f"eta{scale_label}_"
                f"valid_fraction"
            )

            features[
                valid_fraction_name
            ] = H_statistics[
                "valid_fraction"
            ]

    return features


def calculate_curvature_features(
    mol: Chem.Mol,
    conf_id: int,
    elements: list[str],
    scales: list[float],
    other_label: str = "Other",
    gradient_epsilon: float = 1e-12,
) -> dict[str, float]:
    """
    Calculate the complete G5 differential-geometry
    representation for one molecular conformer.

    G5 uses Gaussian element-interactive density fields
    and summarizes their mean and Gaussian curvatures.

    Parameters
    ----------
    mol : Chem.Mol
        Molecule containing a 3D conformer.

    conf_id : int
        RDKit conformer identifier.

    elements : list[str]
        Explicit element vocabulary.

        Elements outside this set are mapped to
        `other_label`.

    scales : list[float]
        Gaussian spatial scales in Angstroms.

    other_label : str
        Category used for rare/unselected elements.

    gradient_epsilon : float
        Minimum gradient magnitude at which the implicit
        density surface is considered regular.

    Returns
    -------
    dict[str, float]
        Fixed-size G5 feature dictionary.
    """

    coords = get_coordinates(
        mol=mol,
        conf_id=conf_id,
    )

    symbols = get_mapped_atom_symbols(
        mol=mol,
        elements=elements,
        other_label=other_label,
    )

    vocabulary = build_element_vocabulary(
        elements=elements,
        other_label=other_label,
    )

    channels = generate_element_channels(
        vocabulary
    )

    features = (
        element_channel_curvature_features(
            coords=coords,
            symbols=symbols,
            channels=channels,
            scales=np.asarray(
                scales,
                dtype=float,
            ),
            gradient_epsilon=gradient_epsilon,
        )
    )

    return features